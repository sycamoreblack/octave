const { chromium } = require('playwright')
const OUT = process.env.OUT
;(async () => {
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } })
  await page.addInitScript(() => localStorage.setItem('worldseed.settings.v1', JSON.stringify({ quality: 'low' })))
  const errors = []
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
  const G = (fn, a) => page.evaluate(fn, a)
  const until = (fn, a, t = 90000) => page.waitForFunction(fn, a, { timeout: t, polling: 200 })
  const settle = async (n = 3) => { const f0 = await G(() => window.__worldseed.game.time); await until(([f0, n]) => window.__worldseed.game.time > f0 + n * 0.05, [f0, n]) }
  await page.goto('http://localhost:5173/')
  await page.fill('#prompt', 'A drowned archipelago at dusk, where old lighthouses guard forgotten songs')
  await page.click('#begin')
  await page.waitForSelector('#card:not(.hidden)', { timeout: 120000 })
  await page.click('#card button.primary')
  await until(() => window.__worldseed.game.mode === 'playing')
  console.log('chat enabled:', await G(() => window.__worldseed.game.chatEnabled))
  const w = await G(() => window.__worldseed.game.world.wanderers[0].position.toArray())
  await G(([x, z]) => window.__worldseed.game.debug().teleport(x, z), [w[0] + 2, w[2] + 1])
  await settle(3)
  await page.keyboard.press('KeyE'); await settle(2)
  console.log('offer shown:', await G(() => !document.querySelector('#say-open').classList.contains('hidden')), '|', await G(() => document.querySelector('#dialogue .more').textContent))
  await page.keyboard.press('Enter'); await settle(2)
  console.log('mode after lines:', await G(() => window.__worldseed.game.mode), '| more:', await G(() => document.querySelector('#dialogue .more').textContent))
  const before = await G(() => window.__worldseed.game.player.position.toArray())
  await page.keyboard.type('Where should I go next? wasd')
  await page.keyboard.press('Enter')
  await until(() => !document.querySelector('#say-input').disabled && document.querySelector('#dialogue .line').textContent.length > 5, null, 30000)
  console.log('you:', await G(() => document.querySelector('#dialogue .you').textContent))
  console.log('reply:', await G(() => document.querySelector('#dialogue .line').textContent))
  const after = await G(() => window.__worldseed.game.player.position.toArray())
  console.log('player moved while typing:', Math.hypot(after[0] - before[0], after[2] - before[2]).toFixed(2))
  await page.screenshot({ path: `${OUT}/p3-chat.png` })
  await page.keyboard.type('Tell me about this place')
  await page.keyboard.press('Enter')
  await until(() => !document.querySelector('#say-input').disabled, null, 30000)
  console.log('reply 2:', await G(() => document.querySelector('#dialogue .line').textContent))
  console.log('history saved:', await G(() => (window.__worldseed.game.progress.chats[0] || []).length))
  await page.keyboard.press('Escape'); await settle(2)
  console.log('after Esc:', await G(() => window.__worldseed.game.mode), 'dialogue hidden:', await G(() => document.querySelector('#dialogue').classList.contains('hidden')))
  // Talk again: returning visit goes to hint then chat.
  await page.keyboard.press('KeyE'); await settle(2)
  console.log('return visit line:', await G(() => document.querySelector('#dialogue .line').textContent.slice(0, 90)))
  console.log('errors', JSON.stringify(errors))
  await browser.close()
})().catch((e) => { console.error(e); process.exit(1) })
