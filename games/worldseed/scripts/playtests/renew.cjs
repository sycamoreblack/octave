const { chromium } = require('playwright')
const OUT = process.env.OUT
;(async () => {
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  const page = await browser.newPage({ viewport: { width: 960, height: 540 } })
  await page.addInitScript(() => localStorage.setItem('worldseed.settings.v1', JSON.stringify({ quality: 'medium', autoQuality: false })))
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  const G = (fn, a) => page.evaluate(fn, a)
  const settle = async (n = 4) => { const f0 = await G(() => window.__worldseed.game.time); await page.waitForFunction(([f0, n]) => window.__worldseed.game.time > f0 + n * 0.05, [f0, n], { polling: 200, timeout: 120000 }) }
  await page.goto('http://localhost:5173/')
  await page.fill('#prompt', process.env.PROMPT)
  await page.click('#begin')
  await page.waitForSelector('#card:not(.hidden)', { timeout: 120000 })
  await page.click('#card button.primary')
  await G(() => { document.querySelector('#hud').style.visibility = 'hidden'; document.querySelector('#toasts').style.display = 'none' })
  const h = await G(() => window.__worldseed.game.world.heart.center.toArray())
  await G(([x, z]) => { const g = window.__worldseed.game; g.debug().teleport(x, z); g.follow.pitch = 0.35; g.follow.distance = 16; g.follow['targetDistance'] = 16 }, [h[0] + 30, h[2] + 30])
  await G(([x, z]) => { const g = window.__worldseed.game; g.follow.yaw = Math.atan2(x - g.player.position.x, z - g.player.position.z) }, [h[0], h[2]])
  await settle(6)
  await page.screenshot({ path: `${OUT}/r-${process.env.TAG}-before.png` })
  await G(() => { const g = window.__worldseed.game; g.world.restoration = 1; g.world.gatherWanderers() })
  await settle(6)
  await page.screenshot({ path: `${OUT}/r-${process.env.TAG}-after.png` })
  console.log('wanderers near heart:', await G(([x, z]) => window.__worldseed.game.world.wanderers.map((w) => Math.round(Math.hypot(w.position.x - x, w.position.z - z))), [h[0], h[2]]))
  console.log('canopies:', await G(() => { let n = 0; window.__worldseed.game.world.scene.traverse((o) => { if (o.name === 'renewal-canopy') n += o.count }); return n }))
  console.log('errors', JSON.stringify(errors))
  await browser.close()
})().catch((e) => { console.error(e); process.exit(1) })
